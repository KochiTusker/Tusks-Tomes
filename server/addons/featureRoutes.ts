/**
 * A feature that ships with the app and always mounts its routes. It has no
 * install state, so neither `isReady()` nor the addons.json toggle applies;
 * whether it is USABLE (CLI on PATH, runner reachable, vault path set) is a
 * detection question its own status endpoint answers. Each feature owns the
 * function that mounts its routes, beside the routers it mounts.
 *
 * Listed in the order they mount, which the route-surface snapshot pins. The
 * names keep the `-addon` suffix because `isAddonLoaded()` and the add-on
 * routes still key on them. A stale configEnabled:false from the add-on era is
 * deliberately ignored rather than migrated, and the old `{configDir}/*.enabled`
 * marker files are no longer consulted (and not deleted).
 */
export type FeatureDefinition = {
  /** Machine-stable identifier; what `isAddonLoaded()` is asked about. */
  name: string
  /** Human-readable name, used in the add-on routes' "part of the app" answers. */
  displayName: string
  description: string
  wip: boolean
  /** Optional /api/docs slug for this feature's user-facing doc. */
  docSlug?: string
  registerRoutes: (app: Express) => void
}

